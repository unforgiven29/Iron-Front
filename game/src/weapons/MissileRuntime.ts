import {
  computeAugmentedProportionalNavigation,
  computeProportionalNavigation,
  computePurePursuitCommand,
  type GuidanceStateEstimate,
  type ProportionalNavigationConfiguration
} from "../physics/guidance/GuidanceLaws.js";
import {
  stepMissile3Dof,
  type MissileAerodynamicModel,
  type MissileEnvironment,
  type MissileState
} from "../physics/ballistics/MissileDynamics.js";

export type MissileGuidanceMethod = "proportional-navigation" | "augmented-proportional-navigation" | "pure-pursuit";
export type MissileSeekerState = "none" | "search" | "acquired" | "track" | "coast" | "failed";
export type MissileFlightPhase = "boost" | "sustain" | "coast" | "terminal" | "detonated" | "self-destructed";

export interface MissileFuzeProfile {
  readonly armingDelaySeconds: number;
  readonly armingDistanceM: number;
  readonly proximityRadiusM: number;
  readonly minimumEventConfidence: number;
  readonly maximumFlightTimeSeconds: number;
}

export interface MissileFuzeEvent {
  readonly kind: "impact" | "proximity";
  readonly eventTimeSeconds: number;
  readonly missDistanceM: number;
  readonly confidence: number;
}

export interface MissileRuntimeModel {
  readonly aerodynamic: MissileAerodynamicModel;
  readonly guidanceMethod: MissileGuidanceMethod;
  readonly guidance: ProportionalNavigationConfiguration;
  readonly fuze: MissileFuzeProfile;
  readonly terminalSeekerRequired: boolean;
}

export interface MissileRuntimeState {
  readonly phase: MissileFlightPhase;
  readonly flight: MissileState;
  readonly launchPositionWorldM: readonly [number, number, number];
  readonly distanceTravelledM: number;
  readonly seekerState: MissileSeekerState;
  readonly lastGuidanceValid: boolean;
  readonly lastGuidanceReason: string;
}

export interface MissileRuntimeStepInput {
  readonly deltaTimeSeconds: number;
  readonly environment: MissileEnvironment;
  readonly guidanceEstimate?: GuidanceStateEstimate;
  readonly seekerState: MissileSeekerState;
  /** Generated by collision/proximity sensing; this module does not inspect world entities. */
  readonly fuzeEvent?: MissileFuzeEvent;
  readonly controlAuthorityFraction?: number;
}

export interface MissileRuntimeStepResult {
  readonly state: MissileRuntimeState;
  readonly guidanceCommand: readonly [number, number, number];
  readonly detonated: boolean;
  readonly selfDestructed: boolean;
}

function distance(a: readonly number[], b: readonly number[]): number {
  return Math.hypot(a[0]! - b[0]!, a[1]! - b[1]!, a[2]! - b[2]!);
}

/** Creates the post-release runtime state from the validated launcher release state. */
export function createMissileRuntimeState(
  initialFlightState: MissileState,
  seekerState: MissileSeekerState = "search"
): MissileRuntimeState {
  return {
    phase: "boost",
    flight: initialFlightState,
    launchPositionWorldM: initialFlightState.positionWorldM,
    distanceTravelledM: 0,
    seekerState,
    lastGuidanceValid: false,
    lastGuidanceReason: "no-guidance-measurement"
  };
}

/**
 * Advances one post-launch step. The function consumes seeker/tracking estimates
 * and external fuze events; it never queries world truth or decides collision.
 */
export function stepMissileRuntime(
  previous: MissileRuntimeState,
  model: MissileRuntimeModel,
  input: MissileRuntimeStepInput
): MissileRuntimeStepResult {
  validateFuze(model.fuze);
  if (!Number.isFinite(input.deltaTimeSeconds) || input.deltaTimeSeconds <= 0) {
    throw new RangeError("Missile runtime delta time must be positive and finite.");
  }
  if (previous.phase === "detonated" || previous.phase === "self-destructed") {
    return {
      state: previous,
      guidanceCommand: [0, 0, 0],
      detonated: previous.phase === "detonated",
      selfDestructed: previous.phase === "self-destructed"
    };
  }

  let commandedAcceleration: readonly [number, number, number] = [0, 0, 0];
  let guidanceValid = false;
  let guidanceReason = "no-guidance-measurement";
  if (input.guidanceEstimate) {
    const guidance = model.guidanceMethod === "augmented-proportional-navigation"
      ? computeAugmentedProportionalNavigation(input.guidanceEstimate, model.guidance)
      : model.guidanceMethod === "pure-pursuit"
        ? computePurePursuitCommand(input.guidanceEstimate, model.guidance)
        : computeProportionalNavigation(input.guidanceEstimate, model.guidance);
    commandedAcceleration = guidance.commandedAccelerationWorldMps2;
    guidanceValid = guidance.valid;
    guidanceReason = guidance.reason;
  }

  const flightStep = stepMissile3Dof(previous.flight, model.aerodynamic, input.environment, {
    deltaTimeSeconds: input.deltaTimeSeconds,
    commandedAccelerationWorldMps2: commandedAcceleration,
    ...(input.controlAuthorityFraction === undefined ? {} : {
      controlAuthorityFraction: input.controlAuthorityFraction
    })
  });
  const flight = flightStep.state;
  const distanceTravelledM = previous.distanceTravelledM +
    distance(flight.positionWorldM, previous.flight.positionWorldM);
  const event = input.fuzeEvent;
  const eventWithinStep = event !== undefined &&
    Number.isFinite(event.eventTimeSeconds) &&
    Number.isFinite(event.missDistanceM) &&
    Number.isFinite(event.confidence) &&
    event.missDistanceM >= 0 && event.confidence >= 0 && event.confidence <= 1 &&
    event.eventTimeSeconds <= flight.elapsedFlightSeconds + 1e-9 &&
    event.eventTimeSeconds >= previous.flight.elapsedFlightSeconds - 1e-9;
  const eventFraction = eventWithinStep
    ? Math.max(0, Math.min(1,
      (event.eventTimeSeconds - previous.flight.elapsedFlightSeconds) / input.deltaTimeSeconds))
    : 0;
  const distanceTravelledAtEventM = previous.distanceTravelledM +
    distance(flight.positionWorldM, previous.flight.positionWorldM) * eventFraction;
  const fuzeArmedAtEvent = eventWithinStep && event!.eventTimeSeconds >= model.fuze.armingDelaySeconds &&
    distanceTravelledAtEventM >= model.fuze.armingDistanceM;
  const fuzeTriggered = fuzeArmedAtEvent &&
    event!.confidence >= model.fuze.minimumEventConfidence &&
    (event!.kind === "impact" || event!.missDistanceM <= model.fuze.proximityRadiusM);

  const selfDestructed = !fuzeTriggered && flight.elapsedFlightSeconds >= model.fuze.maximumFlightTimeSeconds;
  const motorActive = flightStep.diagnostics.activeMotorStageIndices.length > 0 &&
    flight.propellantMassKg > 0;
  const phase: MissileFlightPhase = fuzeTriggered
    ? "detonated"
    : selfDestructed
      ? "self-destructed"
      : model.terminalSeekerRequired && input.seekerState === "track"
        ? "terminal"
        : motorActive
          ? flightStep.diagnostics.activeMotorStageIndices[0] === 0 ? "boost" : "sustain"
          : "coast";

  const state: MissileRuntimeState = {
    phase,
    flight,
    launchPositionWorldM: previous.launchPositionWorldM,
    distanceTravelledM,
    seekerState: input.seekerState,
    lastGuidanceValid: guidanceValid,
    lastGuidanceReason: guidanceReason
  };
  return {
    state,
    guidanceCommand: commandedAcceleration,
    detonated: fuzeTriggered,
    selfDestructed
  };
}

function validateFuze(fuze: MissileFuzeProfile): void {
  if (![fuze.armingDelaySeconds, fuze.armingDistanceM, fuze.proximityRadiusM,
    fuze.minimumEventConfidence, fuze.maximumFlightTimeSeconds].every(Number.isFinite) ||
    fuze.armingDelaySeconds < 0 || fuze.armingDistanceM < 0 || fuze.proximityRadiusM < 0 ||
    fuze.minimumEventConfidence < 0 || fuze.minimumEventConfidence > 1 ||
    fuze.maximumFlightTimeSeconds <= 0) {
    throw new RangeError("Missile fuze profile is invalid.");
  }
}
