/** Panel plane from panel.json (shared with the Blender generator so bezels and gauges coincide). */
const TILT = PANEL.tiltRad, FACE_X = PANEL.faceX, FACE_Z = PANEL.faceZ, PX = PANEL.pxToM;
const [OX, OY] = PANEL.originPx as [number, number];
const onPanel = (u: number, v: number): [number, number, number] => [FACE_X + Math.sin(TILT) * v, u, FACE_Z + Math.cos(TILT) * v];
const placed = new Map(PANEL.instruments.map((i) => [i.id, i]));
const instrument = (id: string, face: InstrumentFace): CockpitPart => {
  const p = placed.get(id);
  if (!p) throw new Error(`panel.json has no instrument "${id}"`);
  const u = (p.x - OX) * PX, v = (p.y - OY) * PX;
  const size: [number, number, number] = "d" in p && p.d !== undefined ? [p.d * PX, p.d * PX, 0] : [(p.w ?? 0) * PX, (p.h ?? 0) * PX, 0];
  return { id, kind: "instrument", positionM: onPanel(u, v), sizeM: size, rotationRad: [0, TILT, 0], color: "#000", instrument: face };
};
const node = (id: string, nodeName: string, binding: NonNullable<CockpitPart["binding"]>): CockpitPart =>
  ({ id, kind: "node", node: nodeName, positionM: [0, 0, 0], sizeM: [0, 0, 0], color: "#000", binding });
const toggle = (switchId: string, positions: readonly string[]) => ({ kind: "switch" as const, switchId, positions, motion: { kind: "rotate" as const, axis: "y" as const, perStep: -55 } });

