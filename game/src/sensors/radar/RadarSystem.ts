import type { SeededRandom } from "../../core/random/SeededRandom.js";
import { BOLTZMANN_CONSTANT_J_PER_K } from "../../physics/radar/RadarPhysics.js";
import type { RadarHardwareState, RadarHardwareThermalModel, RadarEquipmentConfiguration, RadarRangeDopplerScene, RadarResourceSnapshot } from "./RadarRuntime.js";
import {
  advanceRadarHardware,
  synthesizeRangeDopplerFrame
} from "./RadarRuntime.js";
import {
  simulatePulseDopplerCpi,
  type PulseDopplerWaveform
} from "./PulseDopplerSimulation.js";
import {
  detectCaCfar,
  type CaCfarConfiguration,
  type RadarMeasurement,
  type RadarRangeDopplerFrame
} from "./RadarProcessing.js";
import {
  updateRadarTracks,
  type RadarTrack,
  type RadarTrackingConfiguration
} from "./RadarTracking.js";

export interface RadarSystemStepInput {
  readonly hardwareState: RadarHardwareState;
  readonly thermalModel: RadarHardwareThermalModel;
  readonly resources: RadarResourceSnapshot;
  readonly equipment: RadarEquipmentConfiguration;
  readonly scene: RadarRangeDopplerScene;
  readonly random: SeededRandom;
  readonly cfar: CaCfarConfiguration;
  readonly tracking: RadarTrackingConfiguration;
  readonly previousTracks: readonly RadarTrack[];
  readonly timeSeconds: number;
  readonly deltaTimeSeconds: number;
}

export interface RadarSystemStepResult {
  readonly hardwareState: RadarHardwareState;
  readonly transmitPowerFraction: number;
  readonly frame: RadarRangeDopplerFrame | null;
  readonly detections: readonly RadarMeasurement[];
  readonly tracks: readonly RadarTrack[];
  readonly emissionAvailable: boolean;
}

/** Creates a validated, powered-off equipment state with the specified initial health. */
export function createRadarHardwareState(
  thermalModel: RadarHardwareThermalModel,
  initialTemperatureK: number,
  hardwareHealthFraction = 1
): RadarHardwareState {
  if (!Number.isFinite(thermalModel.warmupSeconds) || thermalModel.warmupSeconds < 0 ||
    !Number.isFinite(initialTemperatureK) || initialTemperatureK <= 0 ||
    !Number.isFinite(hardwareHealthFraction) || hardwareHealthFraction < 0 || hardwareHealthFraction > 1) {
    throw new RangeError("Initial radar hardware conditions are invalid.");
  }
  return {
    mode: "off",
    temperatureK: initialTemperatureK,
    warmupRemainingSeconds: thermalModel.warmupSeconds,
    hardwareHealthFraction,
    operatingTimeSeconds: 0
  };
}

/**
 * Single radar equipment vertical slice: resource/thermal lifecycle → RF-return
 * range-Doppler frame → CA-CFAR measurements → uncertain track lifecycle.
 * The scene returns must be generated by physics/radar and contain no world IDs.
 */
export function stepRadarSystem(input: RadarSystemStepInput): RadarSystemStepResult {
  if (!Number.isFinite(input.timeSeconds) || input.timeSeconds < 0 ||
    !Number.isFinite(input.deltaTimeSeconds) || input.deltaTimeSeconds <= 0 ||
    Math.abs(input.scene.acquiredAtSeconds - input.timeSeconds) > 1e-6) {
    throw new RangeError("Radar system time and scene acquisition time must match.");
  }
  const hardware = advanceRadarHardware(
    input.hardwareState,
    input.thermalModel,
    input.resources,
    input.deltaTimeSeconds
  );
  let frame: RadarRangeDopplerFrame | null = null;
  if (hardware.emissionAvailable) {
    const pulseDomain = input.equipment.pulseDomain;
    if (input.equipment.waveform.family === "pulse-doppler" && pulseDomain) {
      const expectedPulseCount = Math.floor(
        input.equipment.waveform.pulseRepetitionFrequencyHz *
        input.equipment.waveform.coherentProcessingIntervalSeconds
      );
      if (pulseDomain.coherentPulseCount !== expectedPulseCount) {
        throw new RangeError("Pulse-domain CPI count must match the equipment PRF and coherent interval.");
      }
      const noisePowerPerComplexSampleW =
        BOLTZMANN_CONSTANT_J_PER_K * input.equipment.receiver.systemTemperatureK *
        input.equipment.waveform.receiverBandwidthHz *
        10 ** (input.equipment.receiver.noiseFigureDb / 10);
      const pulseWaveform: PulseDopplerWaveform = {
        ...pulseDomain,
        centerFrequencyHz: input.equipment.waveform.centerFrequencyHz,
        pulseWidthSeconds: input.equipment.waveform.pulseWidthSeconds,
        pulseRepetitionIntervalSeconds: 1 / input.equipment.waveform.pulseRepetitionFrequencyHz,
        receiverNoisePowerPerComplexSampleW: noisePowerPerComplexSampleW,
        interferencePowerPerComplexSampleW:
          input.scene.interferencePowerW + input.equipment.receiver.clutterPowerPerCellW +
          (input.scene.additionalClutterPowerWPerCell ?? 0)
      };
      const cpi = simulatePulseDopplerCpi(pulseWaveform, {
        scatterers: input.scene.returns.map((echo) => ({
          receivedPowerW: echo.receivedPowerW * hardware.transmitPowerFraction,
          rangeM: echo.rangeM,
          rangeRateMps: echo.rangeRateMps,
          phaseRadians: echo.phaseRadians ?? 0
        })),
        interferers: [],
        acquiredAtSeconds: input.scene.acquiredAtSeconds,
        beamAzimuthDeg: input.scene.beamAzimuthDeg,
        beamElevationDeg: input.scene.beamElevationDeg
      }, input.random);
      frame = cpi.frame;
    } else {
      frame = synthesizeRangeDopplerFrame(
        input.equipment,
        input.scene,
        input.random,
        hardware.transmitPowerFraction
      );
    }
  }
  const detections = frame ? detectCaCfar(frame, input.cfar) : [];
  const trackUpdate = updateRadarTracks(
    input.previousTracks,
    detections,
    input.timeSeconds,
    input.tracking
  );
  return {
    hardwareState: hardware.state,
    transmitPowerFraction: hardware.transmitPowerFraction,
    frame,
    detections,
    tracks: trackUpdate.tracks,
    emissionAvailable: hardware.emissionAvailable
  };
}
